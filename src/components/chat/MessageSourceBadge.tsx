import React from 'react';
import { Globe, Sparkles, Wand2, Brain, type LucideIcon } from 'lucide-react';
import { cn } from '@/lib/utils';

export type MessageSource = 'knowledge' | 'web_search' | 'store_editor' | 'design_generator';

interface SourceConfig {
  label: string;
  icon: LucideIcon;
  className: string;
  tooltip: string;
}

const SOURCE_MAP: Record<MessageSource, SourceConfig> = {
  knowledge: {
    label: 'AI Knowledge',
    icon: Brain,
    className: 'bg-primary/10 text-primary border-primary/20',
    tooltip: "Answer generated from the AI's built-in knowledge",
  },
  web_search: {
    label: 'Web Search',
    icon: Globe,
    className: 'bg-primary/10 text-primary border-primary/20 dark:text-primary',
    tooltip: 'Answer based on real-time web search results',
  },
  store_editor: {
    label: 'Store Editor',
    icon: Wand2,
    className: 'bg-primary/10 text-primary border-primary/20 dark:text-primary',
    tooltip: 'Answer generated by modifying your store',
  },
  design_generator: {
    label: 'Design Generator',
    icon: Sparkles,
    className: 'bg-primary/10 text-primary border-primary/20 dark:text-primary',
    tooltip: 'Answer generated by the design variants engine',
  },
};

export function MessageSourceBadge({ source }: { source: MessageSource }) {
  const cfg = SOURCE_MAP[source];
  if (!cfg) return null;
  const Icon = cfg.icon;
  return (
    <span
      title={cfg.tooltip}
      className={cn(
        'inline-flex items-center gap-1 rounded-full border px-2 py-0.5 text-[10px] font-medium',
        cfg.className
      )}
    >
      <Icon className="h-3 w-3" />
      {cfg.label}
    </span>
  );
}
